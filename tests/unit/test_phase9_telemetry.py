# ── Test 10: Telemetry does NOT affect ranking ──────────────────────────────


def test_no_telemetry_affects_ranking():
    """ranking.py must not import any telemetry, budget, or cost modules.

    Ranking is deterministic-core — telemetry is injected by the wrapper only.
    Checks import statements only (not docstring prose containing 'budget').
    """
    import importlib
    import sys

    ranking_module_path = "app.services.ranking"
    if ranking_module_path in sys.modules:
        ranking_mod = sys.modules[ranking_module_path]
    else:
        try:
            ranking_mod = importlib.import_module(ranking_module_path)
        except ImportError:
            pytest.skip("ranking module not importable in test env")

    source = inspect.getsource(ranking_mod)

    # Check import statements — must NOT import telemetry/budget/llm_usage/cost modules
    import_lines = [
        line.strip() for line in source.splitlines()
        if line.strip().startswith(("import ", "from "))
    ]
    forbidden_imports = ["telemetry", "budget", "llm_usage", "NodeSpan", "BudgetExceeded"]
    for line in import_lines:
        for term in forbidden_imports:
            assert term not in line, (
                f"ranking.py must not import '{term}'. "
                f"Telemetry is injected by graph wrapper, not ranking code. "
                f"Found in: {line}"
            )


# ── Test 11: Session cost accumulation uses HINCRBYFLOAT ─────────────────────


def test_session_cost_accumulation_atomic():
    """accumulate_session_cost() uses Redis HINCRBYFLOAT (not INCRBYFLOAT on strings)."""
    from app.services.budget import accumulate_session_cost

    redis = AsyncMock()
    redis.hincrbyfloat.return_value = 0.005
    redis.hincrby.return_value = 500
    redis.expire.return_value = True

    result = _run(accumulate_session_cost(redis, "session-abc", tokens=500, cost_usd=0.005))

    # Verify HASH operations (not string operations)
    redis.hincrbyfloat.assert_called_once_with(
        "session_cost:session-abc", "total_cost_usd", 0.005
    )
    redis.hincrby.assert_called_once_with(
        "session_cost:session-abc", "total_tokens", 500
    )
    redis.expire.assert_called_once()

    assert result["total_cost_usd"] == 0.005
    assert result["total_tokens"] == 500.0


