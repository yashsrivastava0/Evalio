# ── Test 6: Token accounting correctness ────────────────────────────────────


def test_token_accounting_correct():
    """compute_cost() math is verified for all known models."""
    from app.services.llm_usage import compute_cost

    # gpt-4o-mini: input=0.00015, output=0.00060 per 1k tokens
    cost = compute_cost("gpt-4o-mini", tokens_in=1000, tokens_out=500)
    expected = round((1000 / 1000 * 0.00015) + (500 / 1000 * 0.00060), 6)
    assert cost == expected
    assert cost == 0.00045

    # gpt-4o: input=0.00250, output=0.01000 per 1k tokens
    cost = compute_cost("gpt-4o", tokens_in=2000, tokens_out=1000)
    expected = round((2000 / 1000 * 0.00250) + (1000 / 1000 * 0.01000), 6)
    assert cost == expected

    # Unknown model defaults to 0.0
    cost = compute_cost("unknown-model", tokens_in=5000, tokens_out=3000)
    assert cost == 0.0

    # Zero tokens = zero cost
    cost = compute_cost("gpt-4o-mini", tokens_in=0, tokens_out=0)
    assert cost == 0.0


# ── Test 7: Cost calculation determinism (100 runs identical) ────────────────


def test_cost_calculation_deterministic():
    """Same inputs produce identical results across 100 calls."""
    from app.services.llm_usage import compute_cost

    results = set()
    for _ in range(100):
        cost = compute_cost("gpt-4o-mini", tokens_in=1500, tokens_out=800)
        results.add(cost)

    assert len(results) == 1, f"Non-deterministic results: {results}"
    assert results.pop() == round((1500 / 1000 * 0.00015) + (800 / 1000 * 0.00060), 6)


