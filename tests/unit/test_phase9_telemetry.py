# ── Test 4: Per-request budget enforcement ──────────────────────────────────


def test_budget_enforced_per_request():
    """check_request_budget() raises BudgetExceededError when cost ceiling hit."""
    from app.services.budget import check_request_budget, BudgetExceededError

    # Under budget — no exception
    check_request_budget(accumulated_tokens=100, accumulated_cost=0.001)

    # Over cost budget — exception
    with pytest.raises(BudgetExceededError) as exc_info:
        check_request_budget(accumulated_tokens=100, accumulated_cost=0.05)
    assert exc_info.value.budget_type == "request_cost"

    # Over token budget — exception
    with pytest.raises(BudgetExceededError) as exc_info:
        check_request_budget(accumulated_tokens=20000, accumulated_cost=0.001)
    assert exc_info.value.budget_type == "request_tokens"


