# ── Test 13: Integration — heavy token use triggers budget fallback ──────────


def test_heavy_explanation_triggers_budget_fallback():
    """Integration: when accumulated cost exceeds ceiling, explanation returns template.

    Also tests the final micro-check: telemetry span must be recorded,
    cost_usd=0.0, and budget_exceeded=True.
    """
    from app.services.explanation import explanation_node
    from app.graph import _timed_node

    # Build state with tokens already exceeding budget
    state = {
        "trace_id": "test-trace-fallback",
        "ranked": [
            {"product_id": 10, "final_score": 0.95, "rank": 1, "scores": {
                "performance_score": 0.9, "battery_score": 0.8, "camera_score": 0.7,
                "display_score": 0.85, "build_score": 0.75, "price_score": 0.6,
                "popularity_score": 0.65,
            }, "product_slug": "phone-a", "canonical_title": "Phone A"},
        ],
        "comparison": None,
        "query": "best phone under 30k",
        "validated_ranked_ids": [10],
        "session_id": "heavy-session",
        # Simulate heavy prior usage (well over 0.02 budget)
        "telemetry": {
            "intent": {"tokens_in": 8000, "tokens_out": 4000, "cost_usd": 0.03},
        },
    }

    # LLM client that should NOT be invoked
    llm = MagicMock()
    llm.generate = AsyncMock()

    # Wrap node with telemetry exactly like production graph
    wrapped_node = _timed_node("explanation", lambda s: explanation_node(s, llm_client=llm, redis_client=None))
    result = _run(wrapped_node(state))

    # LLM must not be called
    llm.generate.assert_not_called()

    # Should return valid template explanation with correct usage flags
    explanation = result["explanation"]
    assert "ranked_list" in explanation
    assert len(explanation["ranked_list"]) >= 1
    llm_usage = explanation.get("llm_usage", {})
    assert llm_usage.get("cost_usd", 0.0) == 0.0
    assert llm_usage.get("budget_exceeded") is True

    # Telemetry span must reflect the skip (final micro-check)
    span = result["telemetry"]["explanation"]
    assert span["cost_usd"] == 0.0  # Zero cost recorded
    assert span["budget_exceeded"] is True  # Explicit flag set
    assert span["node_name"] == "explanation"
    assert "duration_ms" in span
